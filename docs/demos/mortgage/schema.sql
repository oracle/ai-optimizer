CREATE OR REPLACE VIEW mortgage_application_summary AS
SELECT
  a.application_reference,
  a.mortgagor_label,
  a.application_type,
  a.property_location,
  a.employment_type,
  a.verified_annual_income + a.verified_other_income AS total_verified_annual_income,
  a.monthly_committed_expenditure,
  a.monthly_household_expenditure,
  a.dependant_count,
  a.property_value,
  a.requested_loan_amount,
  ROUND(a.requested_loan_amount / a.property_value * 100, 2) AS loan_to_value_pct,
  ROUND(a.requested_loan_amount / (a.verified_annual_income + a.verified_other_income), 2) AS loan_to_income_multiple,
  a.mortgage_term_years,
  a.repayment_type,
  a.product_rate
FROM mortgage_applications a;

