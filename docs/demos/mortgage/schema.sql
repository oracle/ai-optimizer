CREATE TABLE lenders (
  lender_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lender_name VARCHAR2(100) NOT NULL
);

CREATE TABLE mortgage_applications (
  application_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_reference VARCHAR2(30) NOT NULL UNIQUE,
  mortgagor_label VARCHAR2(30) NOT NULL UNIQUE,
  lender_id NUMBER NOT NULL REFERENCES lenders(lender_id),
  application_type VARCHAR2(30) NOT NULL,
  property_location VARCHAR2(80) NOT NULL,
  employment_type VARCHAR2(40) NOT NULL,
  verified_annual_income NUMBER(12,2) NOT NULL,
  verified_other_income NUMBER(12,2) DEFAULT 0 NOT NULL,
  monthly_committed_expenditure NUMBER(12,2) NOT NULL,
  monthly_household_expenditure NUMBER(12,2) NOT NULL,
  dependant_count NUMBER(2) DEFAULT 0 NOT NULL,
  property_value NUMBER(12,2) NOT NULL,
  requested_loan_amount NUMBER(12,2) NOT NULL,
  mortgage_term_years NUMBER(2) NOT NULL,
  repayment_type VARCHAR2(30) NOT NULL,
  product_rate NUMBER(5,2) NOT NULL,
  CONSTRAINT ck_mortgage_application_type CHECK (application_type IN ('Purchase', 'Remortgage')),
  CONSTRAINT ck_mortgage_repayment CHECK (repayment_type = 'Capital and interest')
);

